def SUN(cx,cy,r=9):
    return C(cx,cy,r,'#fbbf24','#fbbf24',1)+''.join(L(cx+(r+3)*math.cos(a),cy+(r+3)*math.sin(a),cx+(r+8)*math.cos(a),cy+(r+8)*math.sin(a),'#fbbf24',1.6) for a in [i*math.pi/4 for i in range(8)])
def CANTOP(cx,y,r,gap=24,shape='dome',vent=False):
    """낙하산(윗줄용) : 돔 밑 y, 캔은 y+gap"""
    o=[]
    if shape=='dome': o.append(CHUTE(cx,y,r)); 
    elif shape=='flat': o.append('<ellipse cx="%g" cy="%g" rx="%g" ry="%g" fill="rgba(251,113,133,.30)" stroke="#fb7185" stroke-width="1.5"/>'%(cx,y-6,r,r*0.22))
    elif shape=='square': o.append(P('M%g %g L%g %g L%g %g L%g %g Z'%(cx-r,y-10,cx+r,y-10,cx+r*0.86,y+4,cx-r*0.86,y+4),'#fb7185',1.5,'rgba(251,113,133,.30)'))
    o.append(STR(cx,y-(0 if shape=='dome' else 4),r*(0.9 if shape!='dome' else 1),y+gap)); o.append(CAN(cx-7,y+gap,14,26))
    if vent: o.append(C(cx,y-r*1.05,4,'#0b1424','#fb7185',1.2))
    return ''.join(o)

