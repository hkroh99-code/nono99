DEV='fill="#475569" stroke="#94a3b8" stroke-width="1.3"'
PF={}

def T(x,y,s,c='#cfe0f5',sz=11,anc=None,w=None):
    return '<text x="%g" y="%g" fill="%s" font-size="%g"%s%s>%s</text>'%(x,y,c,sz,(' text-anchor="%s"'%anc if anc else ''),(' font-weight="%s"'%w if w else ''),s)
def R(x,y,w,h,rx=5,f='#475569',s='#94a3b8',sw=1.3,extra=''):
    return '<rect x="%g" y="%g" width="%g" height="%g" rx="%g" fill="%s" stroke="%s" stroke-width="%g"%s/>'%(x,y,w,h,rx,f,s,sw,extra)
def C(cx,cy,r,f='none',s='#94a3b8',sw=1.3):
    return '<circle cx="%g" cy="%g" r="%g" fill="%s" stroke="%s" stroke-width="%g"/>'%(cx,cy,r,f,s,sw)
def L(x1,y1,x2,y2,c='#94a3b8',w=1.2,dash=None):
    return '<path d="M%g %g L%g %g" stroke="%s" stroke-width="%g"%s/>'%(x1,y1,x2,y2,c,w,(' stroke-dasharray="%s"'%dash if dash else ''))
def P(d,c='#94a3b8',w=1.3,f='none',dash=None):
    return '<path d="%s" stroke="%s" stroke-width="%g" fill="%s"%s/>'%(d,c,w,f,(' stroke-dasharray="%s"'%dash if dash else ''))
def AR(x1,y1,x2,y2,c='#fbbf24',w=2):
    dx,dy=x2-x1,y2-y1; Ln=math.hypot(dx,dy) or 1; ux,uy=dx/Ln,dy/Ln
    return L(x1,y1,x2,y2,c,w)+'<path d="M%g %g L%g %g L%g %g Z" fill="%s"/>'%(x2,y2,x2-ux*9-uy*4.5,y2-uy*9+ux*4.5,x2-ux*9+uy*4.5,y2-uy*9-ux*4.5,c)
def DIMH(x1,x2,y,lab,ly=None):
    return L(x1,y,x2,y,'#a78bfa',1.2)+L(x1,y-5,x1,y+5,'#a78bfa',1.2)+L(x2,y-5,x2,y+5,'#a78bfa',1.2)+T((x1+x2)/2,(ly if ly else y-6),lab,'#a78bfa',11.5,'middle','700')
def DIMV(x,y1,y2,lab,lx=None):
    return L(x,y1,x,y2,'#a78bfa',1.2)+L(x-5,y1,x+5,y1,'#a78bfa',1.2)+L(x-5,y2,x+5,y2,'#a78bfa',1.2)+T((lx if lx else x-8),(y1+y2)/2+4,lab,'#a78bfa',11.5,'end','700')
def CAN(x,y,w=14,h=26):
    return R(x,y,w,h,3)+'<rect x="%g" y="%g" width="%g" height="%g" fill="#fbbf24" opacity=".8"/>'%(x,y+h*0.36,w,h*0.14)
def CHUTE(cx,cy,r,col='#fb7185'):
    return '<path d="M%g %g Q%g %g %g %g Z" fill="rgba(251,113,133,.30)" stroke="%s" stroke-width="1.5"/>'%(cx-r,cy,cx,cy-r*1.2,cx+r,cy,col)
def STR(cx,cy,r,cby):
    return L(cx-r,cy,cx,cby,'#94a3b8',1)+L(cx+r,cy,cx,cby,'#94a3b8',1)+L(cx-r/2,cy-r*0.25,cx,cby,'#94a3b8',1)+L(cx+r/2,cy-r*0.25,cx,cby,'#94a3b8',1)
def DROP(cx,top,r,canw=14,canh=26,gap=34):
    """낙하산+줄+캔 : top = 돔의 밑 y. 캔은 top+gap 부터"""
    return CHUTE(cx,top,r)+STR(cx,top,r,top+gap)+CAN(cx-canw/2,top+gap,canw,canh)
def GROUND(x1,x2,y):
    return L(x1,y,x2,y,'#94a3b8',2.2)+''.join(L(x,y,x-6,y+7,'#5b7099',1) for x in range(int(x1)+10,int(x2),16))
def PHONE(x,y,lab=''):
    return R(x,y,26,46,5,'#1e293b','#94a3b8')+C(x+13,y+8,3,'#0f172a','#34d399',1)+(T(x+13,y+34,lab,'#34d399',9,'middle') if lab else '')
def PLOT(x,y,w,h,pts=None,col='#38bdf8'):
    o=[L(x,y+h,x+w,y+h,'#5b7099',1.2),L(x,y,x,y+h,'#5b7099',1.2)]
    if pts: o.append(P('M'+' L'.join('%g %g'%(x+px*w,y+h-py*h) for px,py in pts),col,1.8))
    return ''.join(o)
def WAVES(cx,cy,n=3,r0=8,dr=7,col='#7dd3fc'):
    return ''.join('<path d="M%g %g A%g %g 0 0 1 %g %g" stroke="%s" stroke-width="1.5" fill="none" opacity="%g"/>'%(cx+(r0+dr*i)*0.7,cy-(r0+dr*i)*0.7,r0+dr*i,r0+dr*i,cx+(r0+dr*i)*0.7,cy+(r0+dr*i)*0.7,col,max(.25,.9-i*.2)) for i in range(n))
def RULER(x,y1,y2,lab=''):
    o=[R(x,y1,10,y2-y1,1,'#334155','#94a3b8',1)]
    n=int((y2-y1)/12)
    for i in range(n+1): o.append(L(x,y1+i*12,x+(10 if i%5==0 else 6),y1+i*12,'#94a3b8',1))
    if lab: o.append(T(x+14,(y1+y2)/2,lab,'#9db0cc',10,'start'))
    return ''.join(o)
def BAL(cx,cy,rx=18,ry=22,col='#fbbf24'):
    return '<ellipse cx="%g" cy="%g" rx="%g" ry="%g" fill="rgba(251,191,36,.22)" stroke="%s" stroke-width="1.5"/>'%(cx,cy,rx,ry,col)
def ANT(x,y,h=34):
    return L(x,y,x,y-h,'#94a3b8',2.4)+L(x-10,y-h,x+10,y-h,'#94a3b8',2)+L(x-7,y-h-8,x+7,y-h-8,'#94a3b8',2)+L(x-4,y-h-16,x+4,y-h-16,'#94a3b8',2)
def reg(i, parts, tg): PF[i]=(''.join(parts), tg)


