def CAMERA(x,y,w=40,h=24):
    return R(x,y,w,h,4,'#475569','#94a3b8',1.3)+C(x+w/2,y+h/2,7,'#0f172a','#7dd3fc',1.4)+R(x+4,y-5,10,5,1,'#475569','#94a3b8',1)
def GRID(x,y,w,h,n=6):
    return ''.join(L(x+i*w/n,y,x+i*w/n,y+h,'#5b7099',.8) for i in range(n+1))+''.join(L(x,y+i*h/n,x+w,y+i*h/n,'#5b7099',.8) for i in range(n+1))
def BARS(x,y,w,h,vals,cols):
    n=len(vals); bw=w/n-4
    return ''.join(R(x+i*(bw+4),y+h-v*h,bw,v*h,1,cols[i%len(cols)],'none',0) for i,v in enumerate(vals))+L(x,y+h,x+w,y+h,'#5b7099',1.2)
