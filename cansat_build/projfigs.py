def EGG(cx,cy,s=1.0):
    return '<ellipse cx="%g" cy="%g" rx="%g" ry="%g" fill="#fde68a" stroke="#fbbf24" stroke-width="1.3"/>'%(cx,cy,9*s,12*s)
