    return R(x,y,20,24,3,'#475569','#94a3b8',1.3)+C(x+10,y+12,6,'#0f172a','#fbbf24',1.4)+P('M%g %g q10 -10 0 -20 M%g %g q16 -16 0 -32'%(x+26,y+22,x+34,y+28),'#fbbf24',1.4)
