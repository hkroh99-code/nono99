def card(title, intro, stages, table=None, notes=None):
    h='  <div class="card">\n    <div class="h3">🔎 %s <span class="badge b-high">원리 자세히</span></div>\n    <p class="muted">%s</p>\n    <div class="steps">\n'%(title,intro)
    for t,x in stages: h+='      <div class="step"><b>%s</b> — %s</div>\n'%(t,x)
    h+='    </div>\n'
    if table:
        h+='    <div class="tblwrap" style="max-height:none"><table class="tbl" style="min-width:560px"><thead><tr>'+''.join('<th%s>%s</th>'%(' style="text-align:left"' if i==0 else '',c) for i,c in enumerate(table[0]))+'</tr></thead><tbody>'
        for r in table[1:]: h+='<tr>'+''.join('<td%s>%s</td>'%(' style="text-align:left"' if i==0 else '',c) for i,c in enumerate(r))+'</tr>'
        h+='</tbody></table></div>\n'
    if notes: h+='    <p class="tiny">%s</p>\n'%notes
    return h+'  </div>'

